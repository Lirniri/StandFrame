"""Writes src/lib/AnitaDarin/utils/util/game/data/weapon_components.pluto: every weapon component with the game's label
that holds its name, from Stand-OSS.

    python tools/gen_weapon_components.py STAND_OSS_DIR
    python tools/gen_weapon_components.py STAND_OSS_DIR --weapons-json weapons.json

Without the json the table is read out of STAND_OSS_DIR/scripts/weapon_components.pluto (the 2-element lines
{ "COMPONENT_X", "WCT_X" } between "local components = {" and the closing brace). With the DurtyFree weapons.json
(gta-v-data-dumps; not downloaded here) it does what STAND_OSS_DIR/weapon_components.php does: the label of the
component's TranslatedLabel, else the name_map of that php file, else the component's own name.

The output is generated: change this tool, not the .pluto.
"""

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src/lib/AnitaDarin/utils/util/game/data/weapon_components.pluto"


def from_script(path):
    text = path.read_text(encoding="utf-8")
    block = text[text.index("local components = {"):]
    block = block[:block.index("\n}")]
    return re.findall(r'\{\s*"(COMPONENT_\w+)"\s*,\s*"(\w+)"', block)


def from_json(json_path, php_path):
    name_map = dict(re.findall(r'"(COMPONENT_\w+)"\s*=>\s*"(\w+)"', php_path.read_text(encoding="utf-8")))
    entries = []
    for weapon in json.loads(json_path.read_text(encoding="utf-8")):
        for comp in weapon.get("Components", []):
            label = (comp.get("TranslatedLabel") or {}).get("Name")
            entries.append((comp["Name"], label or name_map.get(comp["Name"], comp["Name"])))
    return entries


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("stand_oss", type=pathlib.Path)
    parser.add_argument("--weapons-json", type=pathlib.Path)
    args = parser.parse_args()

    if args.weapons_json:
        entries = from_json(args.weapons_json, args.stand_oss / "weapon_components.php")
    else:
        entries = from_script(args.stand_oss / "scripts/weapon_components.pluto")

    seen, unique = set(), []
    for name, label in entries:
        if name not in seen:
            seen.add(name)
            unique.append((name, label))

    rows = "\n".join(f'    {{ "{name}", "{label}" }},' for name, label in unique)
    text = f'''-- GENERATED by tools/gen_weapon_components.py from Stand-OSS: change the tool, not this file. Not checked in game.
--
-- Every weapon component of the game with the label that holds its name (a WCT_ label is a text of the game, a name
-- that is not one has no label of its own: it is the component's own name). {len(unique)} components.
--
--     local components = Atdar.util.game.data.weapon_components
--
--     components.get_label("COMPONENT_PISTOL_CLIP_02")   -- "WCT_CLIP2"
--     components.get_text("COMPONENT_PISTOL_CLIP_02")    -- the name in the game's language, "Extended Clip"
--     components.has("COMPONENT_AT_PI_FLSH")             -- true
--     components.get_hash("COMPONENT_AT_PI_FLSH")        -- what the weapon natives take
local module = {{}}

-- {{ component, label }} in the order of the source
module.COMPONENTS = {{
{rows}
}}

-- The label by the component, made once
local labels = nil

-- Makes the table of the labels when it is asked for the first time
local function get_labels(): table

    if labels == nil then
        labels = {{}}

        for _, entry in ipairs(module.COMPONENTS) do
            labels[entry[1]] = entry[2]
        end
    end

    return labels
end

-- How many components there are
function module.count(): int
    return #module.COMPONENTS
end

-- Whether the component is in the table
function module.has(component: string): bool
    return get_labels()[component] ~= nil
end

-- The label that holds the name of the component, nil if it is not in the table
function module.get_label(component: string): ?string
    return get_labels()[component]
end

-- The name of the component in the game's language, nil if it is not in the table or has no label of the game (the
-- label is its own name then)
function module.get_text(component: string): ?string

    local label = get_labels()[component]

    if label == nil or label:sub(1, 4) ~= "WCT_" then
        return nil
    end

    return util.get_label_text(label)
end

-- The hash of the component's name
function module.get_hash(component: string): int
    return util.joaat(component)
end

-- The names of the components that begin with the text ("COMPONENT_AT_" gives the attachments), in the order of the source
function module.find(prefix: string): table

    local found = {{}}

    for _, entry in ipairs(module.COMPONENTS) do
        if entry[1]:sub(1, #prefix) == prefix then
            table.insert(found, entry[1])
        end
    end

    return found
end

return module
'''
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{len(unique)} components -> {OUT.relative_to(ROOT)}")


main()
