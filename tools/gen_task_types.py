"""Writes src/lib/AnitaDarin/natives/memory/task_types.pluto from Stand-OSS: the numbers of the game's tasks
(eTaskType.hpp) and the flags of two tasks (eTaskCombatPedFlags.hpp, eTaskThreatResponseFlags.hpp).

    python tools/gen_task_types.py PATH_TO_STAND_OSS/Stand

The names are the game's own without the TASK_ prefix. The output is generated: change this tool, not the .pluto.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src/lib/AnitaDarin/natives/memory/task_types.pluto"


def read_enum(path, prefix):
    entries = []
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        match = re.match(rf"\s*{prefix}(\w+)\s*=\s*(\d+)\s*,?", line)
        if match:
            entries.append((match.group(1), int(match.group(2))))
    return entries


def table(name, entries, pad, comment):
    lines = [f"-- {comment}", f"module.{name} = {{"]
    for key, value in entries:
        lines.append(f"    {key} = {value},")
    lines.append("}")
    return "\n".join(lines)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = pathlib.Path(sys.argv[1])
    tasks = read_enum(src / "eTaskType.hpp", "TASK_")
    combat = read_enum(src / "eTaskCombatPedFlags.hpp", "COMBAT_PED_")
    threat = read_enum(src / "eTaskThreatResponseFlags.hpp", "TASK_THREAT_RESPONSE_")
    if len({n for n, _ in tasks}) != len(tasks) or len({v for _, v in tasks}) != len(tasks):
        sys.exit("duplicate task names or numbers in the source")

    text = f"""-- GENERATED by tools/gen_task_types.py from Stand-OSS (eTaskType.hpp, eTaskCombatPedFlags.hpp,
-- eTaskThreatResponseFlags.hpp): change the tool, not this file. Not checked in game.
--
-- The numbers of the game's tasks (CTaskTypes) as TASK.<NAME> (the game's name without TASK_), what the memory reads of a
-- task give (Atdar.natives.memory.task.get_type) and what TASK_GET_IS_TASK_ACTIVE takes, and the flags of two tasks.
--
--     local types = Atdar.natives.memory.task_types
--
--     types.TASK.FALL            -- 423
--     types.get_name(423)        -- "FALL", "?423" for a number that has no name
local module = {{}}

{table("TASK", tasks, 0, f"{len(tasks)} tasks")}

-- The flags of the combat task of a ped (eTaskCombatPedFlags)
{table("COMBAT_PED_FLAG", combat, 0, "bits")}

-- The flags of the threat response task (eTaskThreatResponseFlags)
{table("THREAT_RESPONSE_FLAG", threat, 0, "bits")}

-- The names by number, made once from TASK
local names = nil

-- The name of the task with the number, "?" and the number for one that is not in TASK
function module.get_name(task_type: int): string

    if names == nil then
        names = {{}}

        for name, number in pairs(module.TASK) do
            names[number] = name
        end
    end

    return names[task_type] ?? $"?{{task_type}}"
end

return module
"""
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{len(tasks)} tasks, {len(combat)} combat flags, {len(threat)} threat flags -> {OUT.relative_to(ROOT)}")


main()
