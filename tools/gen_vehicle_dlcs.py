def from_json(path, include_g9ec):
    rows = []
    for vehicle in json.loads(path.read_text(encoding="utf-8")):
        if vehicle["DlcName"] == "mpg9ec" and not include_g9ec:
            continue
        vehicle_class = vehicle["Class"].lower()
        if vehicle_class == "compact":
            vehicle_class = "compacts"
        rows.append((vehicle["Name"].lower(), vehicle["Manufacturer"].lower(), vehicle_class, vehicle["DlcName"]))
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--vehicles-json", type=pathlib.Path)
    parser.add_argument("--include-g9ec", action="store_true")
    args = parser.parse_args()

    sample = args.vehicles_json is None
    rows = SAMPLE if sample else from_json(args.vehicles_json, args.include_g9ec)
    unknown = sorted({row[3] for row in rows if row[3] not in DLC_NAMES})
    if unknown:
        raise SystemExit(f"a DLC without a name in DLC_NAMES: {', '.join(unknown)} (add it to the mapping)")

    names = "\n".join(f'    {key} = "{value}",' for key, value in DLC_NAMES.items())
    vehicles = "\n".join(f'    {{ "{n}", "{m}", "{c}", "{d}" }},' for n, m, c, d in rows)
    note = "-- THIS IS A SAMPLE of four vehicles: run the tool with --vehicles-json for the whole list.\n" if sample else ""
    text = (TEMPLATE.replace("{note}", note).replace("{count}", str(len(rows)))
            .replace("@names@", names).replace("@vehicles@", vehicles))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{len(rows)} vehicles ({'sample' if sample else 'from the json'}) -> {OUT.relative_to(ROOT)}")


main()
